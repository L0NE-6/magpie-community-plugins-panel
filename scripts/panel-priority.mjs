#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const defaultSeed = path.join(root, "panel", "triage-seed.json")
const defaultOutput = path.join(root, "panel", "priority.md")
const risks = new Set(["P0", "P1", "P2", "P3"])
const actionLabels = new Map([
  ["直接 review", "Review directly"],
  ["求日志", "Request evidence"],
  ["复现", "Reproduce"],
  ["提交修复", "Prepare fix"],
])

function escapeCell(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\\/g, "\\\\")
    .replace(/\|/g, "\\|")
    .replace(/\r?\n/g, " ")
    .trim()
}

function link(label, url) {
  const text = escapeCell(label).replace(/\[/g, "\\[").replace(/\]/g, "\\]")
  return `[${text}](${url})`
}

function validateSeed(seed) {
  if (seed?.schema_version !== "panel-triage-seed/v1") throw new Error("unsupported triage seed schema")
  if (seed.repository?.full_name !== "magpie-community/plugins") throw new Error("unexpected upstream repository")
  if (!Array.isArray(seed.priority_issues) || !Array.isArray(seed.priority_prs)) {
    throw new Error("triage seed has no priority queues")
  }
  for (const item of [...seed.priority_issues, ...seed.priority_prs]) {
    if (!Number.isSafeInteger(item.number) || item.number < 1) throw new Error("triage item has no issue or PR number")
    if (!risks.has(item.risk)) throw new Error(`triage item #${item.number} has invalid risk ${item.risk}`)
    if (typeof item.title !== "string" || !item.title.trim()) throw new Error(`triage item #${item.number} has no title`)
  }
}

export function renderPriority(seed) {
  validateSeed(seed)
  const repository = seed.repository.full_name
  const summary = seed.summary
  const lines = [
    "# Upstream Priority Queue",
    "",
    `Curated from the public upstream snapshot at \`${seed.generated_at}\`.`,
    "",
    "> This is a triage snapshot, not a claim that every item is reproduced.",
    "> Mergeability, CI and live-account behavior must be verified before action.",
    "",
    "## Backlog",
    "",
    "| Open items | Count |",
    "| :--- | ---: |",
    `| Issues | ${summary.open_issues} |`,
    `| Pull requests | ${summary.open_prs} |`,
    `| Total | ${summary.open_total} |`,
    `| Recognized package clusters | ${summary.package_clusters_total} |`,
    "",
    "## Priority Issues",
    "",
    "| Rank | Risk | Package | Issue | Action | Evidence |",
    "| ---: | :---: | :--- | :--- | :--- | :--- |",
  ]

  for (const item of seed.priority_issues) {
    const issueUrl = `https://github.com/${repository}/issues/${item.number}`
    const action = item.action?.detail || item.action?.primary || ""
    const comments = item.evidence?.comments ?? 0
    const evidence = `${comments} ${comments === 1 ? "comment" : "comments"}; updated ${item.evidence?.updated_at ?? "unknown"}`
    lines.push(
      `| ${item.rank} | **${item.risk}** | \`${escapeCell(item.package || "unclassified")}\` | ${link(`#${item.number} ${item.title}`, issueUrl)} | ${escapeCell(action)} | ${escapeCell(evidence)} |`,
    )
  }

  lines.push(
    "",
    "## Priority Pull Requests",
    "",
    "| Rank | Risk | Package | Pull request | Action | Linked issues |",
    "| ---: | :---: | :--- | :--- | :--- | :--- |",
  )

  for (const item of seed.priority_prs) {
    const pullUrl = `https://github.com/${repository}/pull/${item.number}`
    const linked = Array.isArray(item.linked_issues) && item.linked_issues.length
      ? item.linked_issues.map((number) => `#${number}`).join(", ")
      : "none"
    const action = actionLabels.get(item.action) || item.action
    lines.push(
      `| ${item.rank} | **${item.risk}** | \`${escapeCell(item.package || "unclassified")}\` | ${link(`#${item.number} ${item.title}`, pullUrl)} | ${escapeCell(action)} | ${linked} |`,
    )
  }

  lines.push("", "## Overlap Clusters", "")
  for (const cluster of seed.overlap_and_hold_clusters ?? []) {
    const numbers = cluster.numbers.map((number) => `#${number}`).join(", ")
    lines.push(`- **${escapeCell(cluster.id)}** (${numbers}): ${escapeCell(cluster.reason)}`)
  }

  lines.push(
    "",
    "## Evidence Boundary",
    "",
    ...(seed.source?.evidence_boundaries ?? []).map((boundary) => `- ${escapeCell(boundary)}`),
    "",
    "Generated by `node scripts/panel-priority.mjs`.",
    "",
  )
  return lines.join("\n")
}

function parseArguments(argv) {
  const result = {
    check: false,
    seed: defaultSeed,
    output: defaultOutput,
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === "--check") result.check = true
    else if (argument === "--seed") result.seed = argv[++index] || ""
    else if (argument.startsWith("--seed=")) result.seed = argument.slice("--seed=".length)
    else if (argument === "--out") result.output = argv[++index] || ""
    else if (argument.startsWith("--out=")) result.output = argument.slice("--out=".length)
    else if (argument === "--help" || argument === "-h") result.help = true
    else throw new Error(`unknown argument ${JSON.stringify(argument)}`)
  }
  if (!result.seed || !result.output) throw new Error("seed and output paths must not be empty")
  return result
}

async function main() {
  const options = parseArguments(process.argv.slice(2))
  if (options.help) {
    console.log("usage: node scripts/panel-priority.mjs [--check] [--seed FILE] [--out FILE]")
    return
  }
  const seed = JSON.parse(await readFile(options.seed, "utf8"))
  const markdown = renderPriority(seed)
  if (options.check) {
    const current = await readFile(options.output, "utf8")
    if (current !== markdown) {
      console.error(`panel-priority: ${options.output} is stale`)
      process.exitCode = 1
      return
    }
    console.log(`panel-priority: OK (${options.output})`)
    return
  }
  await writeFile(options.output, markdown, "utf8")
  console.log(`panel-priority: wrote ${options.output}`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(`panel-priority: ${error.stack || error.message}`)
    process.exitCode = 1
  })
}
